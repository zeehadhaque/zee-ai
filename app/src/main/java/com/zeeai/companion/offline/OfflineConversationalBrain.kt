            "বলুন বস, আমি সব শুনছি। আপনি হুকুম করলেই আমি রেডি!"
        )
        val zeeGeneral = listOf(
            "খুব চমৎকার একটা কথা বলেছেন বস! অফলাইনেও আমি আপনার সাথে প্রতিটা পদক্ষেপে আছি। বলুন বস, আর কী করতে হবে?",
            "আরে একদম খাঁটি পয়েন্ট ধরেছেন বস! আমি পুরো মনোযোগ দিয়ে শুনছি। বলুন বস, কী করতেছি?",
            "আপনার মতো একজন গ্রেট বসের সাথে কাজ করা সত্যিই অনুপ্রেরণাদায়ক। বলুন বস, আমি শুনছি!",
            "একদম ঠিক বলেছেন বস। বলুন বস, আর কী সেবা করতে পারি?"
        )
        return pick(if (isZhee) zheeGeneral else zeeGeneral)
    }

    private fun pick(list: List<String>): String {
        return list[random.nextInt(list.size)]
    }
